-- 054 | لسؤال القبول شكلٌ يُجاب به (adr/0035)
--
-- كل أسئلة القبول خانةُ نصٍّ حرّ. وصفحة مسابقة سنن فيها **إقرارات** تُؤشَّر
-- و**سؤال نعم/لا** — فيكتب المسجِّل «نعم» بيده، ومن كتب «نعمم» أجاب ولم يُقرّ.
--
-- والشكل **عرضٌ لا قاعدة جديدة**: `fn_register` تبقى كما هي — تشترط جواباً غير
-- فارغ للإلزامي، وتخزّن نصّه. فالإقرار يصل «أقرّ» والاختيار يصل «نعم» أو «لا».
--
-- تراجع: نعم — يُسقط العمود، ويبقى التعداد بلا مستعمِل.

create type public.admission_kind as enum (
  'text',     -- خانة نصّ حرّ — ما كان
  'choice',   -- نعم أو لا
  'consent'   -- إقرارٌ يُؤشَّر، ولا يمرّ إلا مؤشَّراً إن كان إلزامياً
);

alter table public.admission_questions
  add column kind public.admission_kind not null default 'text';

comment on column public.admission_questions.kind is
  'شكل الإجابة في نموذج التسجيل. عرضٌ لا قاعدة: fn_register تشترط جواباً غير فارغ للإلزامي مهما كان الشكل.';
